// Generates src/data/iconCatalog.ts from the installed @gjsify/adwaita-icons
// package, so the icon library can never drift from what actually renders.
//
// Each module of the package (actions, status, devices, ...) becomes a
// category. Export names are camelCase (`editUndoSymbolic`); they are
// converted to kebab-case icon names (`edit-undo-symbolic`) with exactly the
// same transform src/utils/adwIcons.ts applies when it builds its runtime
// registry, and the same `-rtl` alias skip, so every catalog entry is
// guaranteed to resolve to a registered mask rule.
//
// Usage: node scripts/generate-icon-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
// The package's exports map hides package.json, so resolve a real module.
const pkgDir = dirname(require.resolve('@gjsify/adwaita-icons/actions'));

// Module order mirrors the barrel export (index.ts); labels are the
// GNOME icon-theme context names, as GNOME's Icon Library app shows them.
const MODULES = [
  ['actions', 'Actions'],
  ['categories', 'Categories'],
  ['devices', 'Devices'],
  ['emotes', 'Emotes'],
  ['legacy', 'Legacy'],
  ['mimetypes', 'Mimetypes'],
  ['places', 'Places'],
  ['status', 'Status'],
  ['ui', 'UI'],
];

/** editUndoSymbolic → edit-undo-symbolic — identical to adwIcons.ts. */
const toKebab = (exportName) =>
  exportName.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const categories = [];
const seen = new Set();
for (const [module, label] of MODULES) {
  const source = readFileSync(join(pkgDir, `${module}.ts`), 'utf-8');
  const icons = [];
  for (const match of source.matchAll(/^export const ([A-Za-z0-9]+) =/gm)) {
    const kebab = toKebab(match[1]);
    // `applicationExitSymbolicRtl` is an RTL alias of the same artwork;
    // adwIcons.ts skips these too, so they could never render anyway.
    if (kebab.endsWith('-rtl')) continue;
    if (seen.has(kebab)) continue;
    seen.add(kebab);
    icons.push(kebab);
  }
  icons.sort();
  categories.push({ id: module, label, icons });
}

const total = categories.reduce((sum, category) => sum + category.icons.length, 0);

const banner =
  `// Auto-generated by scripts/generate-icon-catalog.mjs — do not edit.\n` +
  `// Every symbolic icon exported by the installed @gjsify/adwaita-icons\n` +
  `// package (${total} icons), grouped by the package's module = icon-theme\n` +
  `// context. Regenerate with: node scripts/generate-icon-catalog.mjs\n`;

const body = `${banner}
export interface IconCatalogCategory {
  /** Package module name, e.g. "actions". */
  id: string;
  /** Display label, e.g. "Actions". */
  label: string;
  /** Kebab-case icon names including the -symbolic suffix. */
  icons: string[];
}

export const ICON_CATALOG: IconCatalogCategory[] = ${JSON.stringify(categories, null, 2)};

export const ALL_CATALOG_ICONS: string[] = ICON_CATALOG.flatMap(
  (category) => category.icons,
).sort();

export const ICON_CATALOG_TOTAL = ${total};
`;

writeFileSync(join(root, 'src/data/iconCatalog.ts'), body);
console.log(
  `Wrote src/data/iconCatalog.ts — ${total} icons in ${categories.length} categories:`,
  categories.map((c) => `${c.id} ${c.icons.length}`).join(', '),
);
