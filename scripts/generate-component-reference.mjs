/**
 * Generate docs/components.md from the code that defines the component set.
 *
 *   npx tsx scripts/generate-component-reference.mjs
 *
 * Users and agents need a browsable list of what this tool can build: every
 * widget, the GTK class it exports as, the slots it offers, the properties the
 * inspector edits, and what it legally contains. Generating it from
 * LEGAL_CHILDREN, LEGAL_SLOTS, WIDGET_SCHEMAS and the GIR tables means the
 * reference cannot drift from the implementation.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { LEGAL_CHILDREN, LEGAL_SLOTS } from '../src/types/mockup.ts';
import { WIDGET_SCHEMAS } from '../src/schemas/widgetSchemas.ts';
import { GTK_PROPERTY_DATA } from '../src/data/gtkProperties.ts';
import { widgetClassForType } from '../src/utils/blueprint.ts';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const types = Object.keys(LEGAL_CHILDREN).sort();

const lines = [
  '# Component reference',
  '',
  '_Generated by `scripts/generate-component-reference.mjs` — do not hand-edit._',
  '',
  'Every widget Protota can render, insert, and export. Use it to find what to',
  'build with, whether from the palette, the agent API, or a Blueprint import.',
  '',
  '- **Exports as** — the GTK/libadwaita class written by `mockupToBlueprint`.',
  '- **Slots** — named child positions (`addWidget(type, { slot })`).',
  '- **Properties** — what the inspector and the builder can set.',
  '- **Accepts** — legal children; generic containers accept any widget.',
  '',
  `${types.length} components.`,
  '',
];

for (const type of types) {
  const exportClass = widgetClassForType(type);
  const slots = LEGAL_SLOTS[type] ?? [];
  const schema = WIDGET_SCHEMAS[type] ?? [];
  const children = LEGAL_CHILDREN[type] ?? [];
  const gtkProperties = exportClass ? GTK_PROPERTY_DATA.classes[exportClass] : undefined;

  lines.push(`## \`${type}\``);
  lines.push('');
  lines.push(`- **Exports as:** \`${exportClass ?? '—'}\`${gtkProperties ? '' : ' _(no introspection data)_'}`);
  lines.push(`- **Slots:** ${slots.length ? slots.map((slot) => `\`${slot}\``).join(', ') : '—'}`);
  lines.push(`- **Properties:** ${schema.length ? schema.map((field) => `\`${field.key}\` (${field.type})`).join(', ') : '—'}`);
  lines.push(children.length >= 20
    ? '- **Accepts:** any widget (generic container)'
    : `- **Accepts:** ${children.length ? children.map((child) => `\`${child}\``).join(', ') : 'nothing (leaf)'}`);
  lines.push('');
}

const outPath = join(repoRoot, 'docs/components.md');
writeFileSync(outPath, lines.join('\n'));
console.log(`${outPath} — ${types.length} components`);
